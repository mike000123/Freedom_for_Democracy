class Command(BaseCommand):
    help = "Ερωτήματα δείγματος για το ερωτηματολόγιο προτιμήσεων και θέσεις στις προτάσεις των κομμάτων δείγματος."

    def handle(self, *args, **options):
        made = 0
        for topic in Topic.objects.all():
            spec = QUESTIONS.get(topic.name)
            if not spec:
                continue
            question, created = PrefQuestion.objects.get_or_create(topic=topic, defaults={"text": spec[0]})
            if created or not question.options.exists():
                for i, text in enumerate(spec[1]):
                    PrefOption.objects.create(question=question, text=text, order=i)
                made += 1
        # Θέσεις μόνο στις προτάσεις των κομμάτων δείγματος και μόνο όπου δεν έχει δηλωθεί ήδη θέση.
        assigned = 0
        for prop in Proposal.objects.filter(stance__isnull=True, party__is_example=True).select_related("topic"):
            question = getattr(prop.topic, "pref_question", None)
            options = list(question.options.all()) if question else []
            if options:
                prop.stance = options[(prop.party_id + prop.topic_id) % len(options)]
                prop.save(update_fields=["stance"])
                assigned += 1
        self.stdout.write(self.style.SUCCESS(f"Ερωτηματολόγιο: {made} θέματα με ερώτημα, {assigned} προτάσεις δείγματος με θέση."))
